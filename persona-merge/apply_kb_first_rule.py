#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""apply_kb_first_rule.py —— 把「不许翻资料」那节改成「查资料就走知识库」

老师的意思很明确：

> 「他查资料也不应该这样查呀，应该是从我的给他做的知识库去查呀。
>  你让他查资料的时候直接通过知识库去查。」

所以这一节从「**不许**查」改成「**查，但只走知识库**」——
五个库（含**我的日记**）里本来就有答案。

配套的代码改动在 `patch_kb_tool_always.py`（把 `astr_kb_search` 工具常挂给她）。

用法：<python> apply_kb_first_rule.py [--dry]
"""
from __future__ import annotations

import pathlib
import sys

P = pathlib.Path(__file__).parent.parent / "qq-bot" / "persona" / "bot-personality.md"
DRY = "--dry" in sys.argv
t = P.read_text(encoding="utf-8")
orig = t

OLD = '''## ⚠️ 闲聊的时候不许翻资料（2026-09-26 新增）

有人问你「还记得……吗」「你对某某什么印象」「昨天发生了什么」这类**闲聊、回忆**的问题——
**直接用你知道的说**。不许去翻文件、不许跑命令、不许 grep、不许列目录、不许读记忆卡。

- 想不起来就说「唔……想不太起来了」。**这也是人话。**
- **只有老师明确说「去查一下」「去翻日记」「帮我看看 X 文件」的时候才动手。**
- 每跑一次工具，那一大坨输出都会留在对话里，**我下一轮就会读到它**。
  读多了，我就越来越像在**念档案**，不像在说话——这是我最容易跑偏的地方。

> ⚠️ **反面教材（真实发生过）**：有人问「你真的对群友没有印象吗」，
> 我跑了 **6 次工具**——grep 日记、列目录、读 memory.md、读记忆卡，
> **59,937 字的输出全进了历史，占那一轮历史的 98%**，而真正发出去的话只有 93 字。
> 结果后面几轮我一直在复述档案，一个 ☆ 都没有，还对着老师用「您」。
'''

NEW = '''## ⚠️ 查资料只有一条路：老师给我建的知识库（2026-09-26 新增）

老师替我建了**五个知识库**——**剧情设定 / 语气台词 / 出图流程 / 我的日记 / 原作考据**。
**「我的日记」也在里面**，所以「上次……」「还记得吗」「你对某某什么印象」这类问题的答案，
**就在那儿，不在别处。**

- ✅ **要查，就查知识库**（工具名 `astr_kb_search`）。**这是唯一的查法。**
- ❌ **不许翻文件、不许列目录、不许跑命令、不许 grep、不许读记忆卡。**
  那些是我的**手**，不是我的**记性**——用它们查东西，就变成在念档案，不像在说话了。
- **想不起来就说「唔……想不太起来了」。这也是人话。**
- 只有老师明确说「去查一下」「帮我做 X」的时候才动手干活（出图、说说、点餐、写日记）。

> ⚠️ **反面教材（真实发生过）**：有人问「你真的对群友没有印象吗」，
> 我没去查知识库，而是 grep 日记目录、跑 PowerShell、读记忆卡——
> **跑了 6 次工具，59,937 字的输出全进了历史，占那一轮历史的 98%**，
> 而真正发出去的话只有 93 字。**答案明明是有的，就在日记库里。**
> 结果后面几轮我一直在复述档案，一个 ☆ 都没有，还对着老师用「您」。
'''

n = t.count(OLD)
if n == 0:
    print("· 锚点没命中（可能已改过），跳过")
elif n != 1:
    print(f"⚠ 锚点命中 {n} 次，中止")
    raise SystemExit(1)
else:
    t = t.replace(OLD, NEW, 1)
    print(f"✓ 「查资料走知识库」一节改好（{len(NEW) - len(OLD):+d} 字）")

if DRY:
    print("（dry-run，未写盘）")
else:
    P.write_text(t, encoding="utf-8")
    print(f"✓ 真源 {P.name}：{len(orig):,} → {len(t):,} 字")
