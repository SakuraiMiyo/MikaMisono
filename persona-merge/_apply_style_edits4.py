for name, old, new in (("口头禅一节", ANCHOR, NEW_SECTION),
                       ("称呼表", OLD_CALL, NEW_CALL)):
    n = t.count(old)
    if new in t and n == 0:
        print(f"· {name}：已是目标状态，跳过")
        continue
    if n != 1:
        raise SystemExit(f"✗ {name}：锚点出现 {n} 次（应为 1），中止")
