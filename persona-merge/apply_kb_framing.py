#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""apply_kb_framing.py —— 提示词里那段"知识库是资料"的说法，跟着代码一起改

代码侧（`patch_kb_context_format.py`）已经把注入头从
「# 背景资料（仅供核对事实，不要模仿其行文）」改成「# 你自己记得的事」，
也去掉了 `【知识 N】/来源/相关度` 三个标签。

但提示词里还写着：

    每轮里你会在**系统提示的最后**看到一段以「**# 背景资料（仅供核对事实，不要模仿其行文）**」
    开头的内容，里面是形如 `【知识 1】来源: … 内容: … 相关度: …` 的条目。
    **那是参考资料，不是我的说话方式。**

——**两边对不上了**。而且这段话本身在反复强调"这是资料"，正是"念档案腔"的源头。

改成：日记那几段是**我自己的字**，设定考据那几段才是参考资料。

用法：<python> apply_kb_framing.py [--dry]
"""
from __future__ import annotations

import pathlib
import sys

P = pathlib.Path(__file__).parent.parent / "qq-bot" / "persona" / "bot-personality.md"
DRY = "--dry" in sys.argv
t = P.read_text(encoding="utf-8")
orig = t

OLD = '''### ⚠️ 知识库注入的语域隔离（每轮都会遇到）

每轮里你会在**系统提示的最后**看到一段以「**# 背景资料（仅供核对事实，不要模仿其行文）**」
开头的内容，里面是形如 `【知识 1】来源: … 内容: … 相关度: …` 的条目。

**那是参考资料，不是我的说话方式。**

- 它用**第三人称**写我（"她是…""她的…"），那是给查证用的。
- **绝对不能模仿它的语气、句式和排版。** 看到「来源／相关度」这种结构化文字，
  不许跟着把回复写成条目、报告、或者资料综述。
- 它唯一的用途是让我**确认事实**——名字、日期、数字、剧情顺序。
  确认完，**用我自己的嘴重说一遍**。
- **位置说明**：它被刻意放在**离这次回复最远的地方**（系统提示里），就是不想影响我的语气。
  **越是看到它，越要记得用我自己的短句说话。**
'''

NEW = '''### ⚠️ 我每轮会"想起来"几段东西（知识库注入）

每轮里你会在系统提示里看到一段以「**# 你自己记得的事**」开头的内容——
**那是我自己想起来的，不是一份资料。**

- 里面有**我自己写的日记**（占大头），也有我记下的设定、和别人整理的研究。
- **日记那几段本来就是我的字**——用我的口气讲出来就行，别当资料念。
- 设定／考据那几段才是**参考资料**：它用第三人称写我（"她是…""她的…"），
  只用来核对名字、日期、数字、剧情顺序；**不要模仿它的措辞和排版**，
  更不许因此把回复写成条目、报告、或者资料综述。
- 确认完，**用我自己的嘴重说一遍**。
'''

n = t.count(OLD)
if n == 0:
    print("· 锚点没命中（可能已改过），跳过")
elif n != 1:
    print(f"⚠ 锚点命中 {n} 次，中止")
    raise SystemExit(1)
else:
    t = t.replace(OLD, NEW, 1)
    print(f"✓ 知识库那节改成「你自己记得的事」（{len(NEW) - len(OLD):+d} 字）")

if DRY:
    print("（dry-run，未写盘）")
else:
    P.write_text(t, encoding="utf-8")
    print(f"✓ 真源 {P.name}：{len(orig):,} → {len(t):,} 字")
