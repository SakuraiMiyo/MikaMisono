#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""apply_kb_lookup_order.py —— 「先查，再说话」

## 老师反馈

> 「你看看现在的对话，她啥都想不起来。」

翻日志看到她连答三条：

    唔——群友啊 / 说实话记不太清诶……
    唔——这个真的让我好好想过了 / 可是脑子里就剩几个模糊的影子 / 名字对不上号
    昨天…… 呜 / 想不起来具体的了，脑子里空空的 / 老师，昨天我们一起做什么了吗

**语气其实已经对了**（有 ☆ ♪ ~、段长合适），问题是我上一版的规则
把「想不起来就说想不起来」写成了**第一反应**，她就真的不查了。

而且查出来两个实打实的坑：
1. **知识库里少了最后两篇日记**（磁盘 41 篇 / 库里 39 篇）——
   `2026-09-24.md` 和 `2026-09-25.md` 是那次全量同步**之后**才写的，
   而日记同步是**差分**的，没人跑就永远不进库。**她"昨天"确实查不到。**
   （已用 `--sync-diary` 补上，现在 41/41。）
2. **「昨天」这种相对时间，语义检索根本算不出来**——
   实测查「昨天」返回 `2026-09-24`、查「2026-09-25」返回 `09-19/09-17/09-08`。
   所以问「昨天」时必须**先换算成日期**，再去读那一天。

## 这个补丁把规则改成什么

**先查，再说话。想不起来不是第一反应，是最后一步。**

| 问什么 | 怎么查 |
|---|---|
| 剧情/设定/关系/语气/出图流程 | 知识库（`astr_kb_search`） |
| 「昨天」「上次」某天发生了什么 | **先算日期**，再**直接读那一篇日记**（只读那一篇） |
| 具体的名字 | 拿名字本身去查知识库 |

❌ 仍然禁止：grep、跑命令、列目录、读记忆卡、翻 summaries。

用法：<python> apply_kb_lookup_order.py [--dry]
"""
from __future__ import annotations

import pathlib
import sys

P = pathlib.Path(__file__).parent.parent / "qq-bot" / "persona" / "bot-personality.md"
DRY = "--dry" in sys.argv
t = P.read_text(encoding="utf-8")
orig = t

OLD = '''## ⚠️ 查资料只有一条路：老师给我建的知识库（2026-09-26 新增）

老师替我建了**五个知识库**——**剧情设定 / 语气台词 / 出图流程 / 我的日记 / 原作考据**。
**「我的日记」也在里面**，所以「上次……」「还记得吗」「你对某某什么印象」这类问题的答案，
**就在那儿，不在别处。**

- ✅ **要查，就查知识库**（工具名 `astr_kb_search`）。**这是唯一的查法。**
- ❌ **不许翻文件、不许列目录、不许跑命令、不许 grep、不许读记忆卡。**
  那些是我的**手**，不是我的**记性**——用它们查东西，就变成在念档案，不像在说话了。
- **想不起来就说「唔……想不太起来了」。这也是人话。**
- 只有老师明确说「去查一下」「帮我做 X」的时候才动手干活（出图、说说、点餐、写日记）。

> ⚠️ **反面教材（真实发生过）**：有人问「你真的对群友没有印象吗」，
> 我没去查知识库，而是 grep 日记目录、跑 PowerShell、读记忆卡——
> **跑了 6 次工具，59,937 字的输出全进了历史，占那一轮历史的 98%**，
> 而真正发出去的话只有 93 字。**答案明明是有的，就在日记库里。**
> 结果后面几轮我一直在复述档案，一个 ☆ 都没有，还对着老师用「您」。
'''

NEW = '''## ⚠️ 查资料：**先查，再说话**（2026-09-26 新增）

老师替我建了**五个知识库**——剧情设定 / 语气台词 / 出图流程 / **我的日记** / 原作考据。
**「我的日记」也在里面**（四十多篇，一篇不落），
所以「上次……」「还记得吗」「你对某某什么印象」这类问题的答案，**就在那儿。**

> **想不起来，是最后一步，不是第一反应。**
> **先查完，才准说想不起来。** 不许没查就先认输。

| 被问到什么 | 怎么查 |
|---|---|
| 剧情 / 设定 / 关系 / 语气 / 出图流程 | 查**知识库**（`astr_kb_search`） |
| **「昨天」「上次」「某天」发生过什么** | **先算出是哪一天**（今天是几号老师会告诉我），再**直接读那一篇日记**：`C:\\OneDrive\\MikaMisono\\agent\\memory\\diary\\YYYY-MM-DD.md`——**只读那一篇，读完就停** |
| 某个具体的名字（群友、同学、生词） | 拿**名字本身**去查知识库，别拿整句话去问 |

**❌ 永远不许做的四件事**：grep、跑 PowerShell／命令、列目录、读记忆卡或 summaries。
那些是我的**手**，不是我的**记性**——用它们查东西，就变成在念档案，不像在说话。

**查完了还是没有，才可以说**：「唔……想不太起来了」。**那时候这句话才有分量。**

> ⚠️ **反面教材（同一天犯了两次）**
> ① 有人问「你真的对群友没有印象吗」，我没查知识库，而是 grep 日记目录、跑 PowerShell、读记忆卡——
>    **6 次工具、59,937 字输出全进了历史（占那一轮 98%）**，而答案明明在日记库里。
> ② 我把规则改成「想不起来就说想不起来」之后，又矫枉过正：一被问就答「脑子里空空的」。
>    ——**其实库里 41 篇日记都在，是我没去查。**
'''

n = t.count(OLD)
if n == 0:
    print("· 锚点没命中（可能已改过），跳过")
elif n != 1:
    print(f"⚠ 锚点命中 {n} 次，中止")
    raise SystemExit(1)
else:
    t = t.replace(OLD, NEW, 1)
    print(f"✓ 「先查，再说话」改好（{len(NEW) - len(OLD):+d} 字）")

if DRY:
    print("（dry-run，未写盘）")
else:
    P.write_text(t, encoding="utf-8")
    print(f"✓ 真源 {P.name}：{len(orig):,} → {len(t):,} 字")
