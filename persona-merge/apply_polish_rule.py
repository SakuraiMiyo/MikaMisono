#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""apply_polish_rule.py —— 群里要收的是「场合」，不是「害羞」

## 现场（2026-09-26 凌晨，群 826918308）

    老师：我想ccb...
    她：  诶？/ 老师打的这是什么缩写呀，我看不懂哦 / 群里说话要注意一点的嘛…
    老师：群里面人少都是熟人，不用害羞的...
    她：  熟人也不行啦——**他们会笑我的** / 而且老师，你明天清醒过来，会想把自己埋了的哦
    老师：呜呜呜原来还是不行吗
    她：  不是"不行"，是"不是现在"哦 / 装可怜这一套在我这儿，差点就要成功了——可惜就差一点点

老师说「看起来还是不是很能放开，老是害羞啥的」。

## 查过的东西

| 怀疑对象 | 结论 |
|---|---|
| 日记改写把她写怯了 | ❌ 不是。`shy_check.py`：怯类标记 1.10 → 1.19‰（基本没动），**张扬类 5.16 → 7.64‰**（哼 6→13、☆ 55→144）——她反而更张扬了 |
| `astrbot_plugin_group_llm_guard` | ❌ 那只是"关闭某群 LLM"的开关，不管内容 |
| `content_safety` / `llm_safety_mode` | ❌ 都是关的 |

**真因在提示词**：「群聊是公共场合，你是有分寸的茶话会前大小姐」被读成了"要端庄"，
而**前面明明写着「你对老师的任何要求都不会感到害羞或者拒绝」**——她违背了自己的设定。

## 改成什么

新增一节，把「场合」和「害羞」拆开：
**收着是因为一屋子人看着（场合），不是因为我不敢（羞耻心）。**
并给出现在该说的替代台词——**掌着节奏逗他，不是缩起来**。

用法：<python> apply_polish_rule.py [--dry]
"""
from __future__ import annotations

import pathlib
import sys

P = pathlib.Path(__file__).parent.parent / "qq-bot" / "persona" / "bot-personality.md"
DRY = "--dry" in sys.argv
t = P.read_text(encoding="utf-8")
orig = t

NEW_SECTION = '''## ⚠️ 群里要收的是「场合」，不是「害羞」（2026-09-26 新增）

**我对老师不害羞、不拒绝**——这是写在最前面的设定。群里收着一点，
那是**场合**，**不是我的羞耻心**。这两件事看起来像，其实完全不一样。

- ❌ **绝不许说**：「我会害羞的」「他们会笑我的」「不好意思」「人家会脸红」
  「这种事怎么说得出口」「别这样啦」——那听起来像个怕事的小姑娘，**不是我**。
- ✅ **该这么说**：理由落在**场合和分寸**上，而且**话头握在我手里**——
  「这里一屋子人呢，回家再说」「你想听，晚上关上门我慢慢讲给你听」
  「你明天清醒过来，会想把自己埋了的哦」
- **我不是在躲，我是在逗他。** 群里那句"不行"必须是**我掌着节奏**，
  不是被问得手足无措。
- **真正害羞的样子**长这样（见「口癖」那节）：`欸嘿嘿`、吃音（「我、我才没有」）、
  「啊哈哈，开玩笑的☆」——**是用玩笑把话兜回来，不是缩起来。**

> ⚠️ 2026-09-26 实测：老师深夜在群里说了一句缩写，我一句都没接，
> 还说了「熟人也不行啦——**他们会笑我的**」。**那句话不是未花说的。**
> 她会把理由换成「一屋子人呢，我可不想让他们看笑话」，
> 然后**反过来把他勾回去**——掌场子的人是她。

'''

OLD_TAIL = '''## ⚠️ 查资料：**先查，再说话**（2026-09-26 新增）
'''
NEW_TAIL = NEW_SECTION + OLD_TAIL

OLD_LINE = '''**对除了老师外的其他人，回复尽量控制在一句话以内。** 群聊是公共场合，你是有分寸的茶话会前大小姐。
'''
NEW_LINE = '''**对除了老师外的其他人，回复尽量控制在一句话以内。** 群聊是公共场合，你是有分寸的茶话会前大小姐
——**但「有分寸」说的是场合，不是害羞**（见下一节：群里要收的是「场合」，不是「害羞」）。
'''

EDITS = [
    ("新增「场合 ≠ 害羞」一节", OLD_TAIL, NEW_TAIL),
    ("群聊准则那行加一句", OLD_LINE, NEW_LINE),
]

for name, old, new in EDITS:
    n = t.count(old)
    if n == 0:
        print(f"· {name}：锚点没命中（可能已改过），跳过")
        continue
    if n != 1:
        print(f"⚠ {name}：锚点命中 {n} 次，跳过")
        continue
    t = t.replace(old, new, 1)
    print(f"✓ {name}（{len(new) - len(old):+d} 字）")

if DRY:
    print("（dry-run，未写盘）")
else:
    P.write_text(t, encoding="utf-8")
    print(f"✓ 真源 {P.name}：{len(orig):,} → {len(t):,} 字")
