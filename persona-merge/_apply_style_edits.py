for name, old, new in EDITS:
    if new in t and old not in t:
        print(f"· {name}：已是目标状态，跳过")
        continue
    n = t.count(old)
    if n != 1:
        raise SystemExit(f"✗ {name}：锚点出现 {n} 次（应为 1 次），中止")
    t = t.replace(old, new)
    print(f"✓ {name}")

# ④ 删掉整节「硬配额」——它和「输出格式」那一节说的是同一件事，而且「默认 1–3 条」
#    和上面的「2–4 条」互相打架。
START = '### 硬配额（比"要像我"有用得多）'
END = '### 符号（**点缀，不是底色**）'
i, j = t.find(START), t.find(END)
if i == -1:
    print("· 硬配额：已删除，跳过")
else:
    assert j > i, "找不到「符号」节，中止"
    removed = t[i:j]
    t = t[:i] + t[j:]
    print(f"✓ 删除「硬配额」整节（{len(removed)} 字，含 {removed.count(chr(10))} 行）")

assert t != orig, "什么都没改"
P.write_text(t, encoding="utf-8")
n_hard = t.count("硬配额")
print(f"\n✓ 写入 {P.name}：{len(orig):,} → {len(t):,} 字")
print(f"  「硬配额」残留：{n_hard} 次")
