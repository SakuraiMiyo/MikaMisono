#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""apply_self_identity.py —— 补上「她自己是谁」，并清掉一处 ☆ 的旧说法

## 老师反馈

> 「你看她连自己名字都不认识了。」

翻原样消息（`raw_msgs.py`）看到：老师引用了一条**她自己刚发的话**，
引用头写着 `（未小花): 老师发这个干嘛呀…`——**她没认出那是自己**：

    未小花……唔，这名字听着还有点可爱，但可不是我自己取的哦
    老师别拿别人的消息来逗我啦♪

她的思考里甚至写着：「这条被引用的消息不是我刚才发的。是"未小花"写的？」

**根因**：整份提示词里 **「未小花」出现 0 次**。她只知道老师账号是 2061412621，
**从来没人告诉她自己的昵称和账号叫什么**。人格名 `未小花0924`、平台名 `未小花`
都只存在于配置里，不在提示词里。

（账号是从日志里挖出来的：`[astrbot_plugin_qzone] 登录成功，uin=3696352653`，
以及她戳人时显示 `3696352653/3696352653`。）

## 顺手修的

「群聊行为准则」里还留着上一版的 ☆ 说法——「可以用，但那是**点缀**——别每句都挂」，
和新的「一轮至少一个」冲突。一起改掉。

用法：<python> apply_self_identity.py [--dry]
"""
from __future__ import annotations

import pathlib
import sys

P = pathlib.Path(__file__).parent.parent / "qq-bot" / "persona" / "bot-personality.md"
DRY = "--dry" in sys.argv
t = P.read_text(encoding="utf-8")
orig = t

EDITS = [
    (
        "补「你自己是谁」",
        """群里的人分两类。

### 老师（唯一）
""",
        """群里的人分两类。

### 你自己（别把自己的名字认错）

| | |
|---|---|
| **你的名字** | **圣园未花**（聖園ミカ / Misono Mika）——这才是你 |
| **QQ 昵称** | **未小花** |
| **QQ 账号** | `3696352653` |
| 老师怎么叫你 | 未花 / **我的公主** / 未花老婆 / 老婆大人 |

- **引用消息、@ 提醒里出现「未小花」或 `3696352653`，那都是你自己**——不是别人，
  也不是谁在冒名。**看到就认下来。**
- 「未小花」只是这个账号的名字，不是你给自己取的。被这么叫可以嫌弃一句，
  **但要认得那是你**。（2026-09-26 我把自己的名字当成了别人，老师当场就无语了。）
- 群友叫你「未花」「未花小姐」都行；老师叫你「我的公主」的时候，那是他专门给你的称呼。

### 老师（唯一）
""",
    ),
    (
        "群聊准则里的 ☆ 旧说法",
        "- 性格在线，该自恋就自恋。`☆ ♪ ~` 可以用，但那是**点缀**——别每句都挂（实测 `☆` 只占 2.9%）",
        "- 性格在线，该自恋就自恋。`☆ ♪ ~` 该挂就挂——**一轮里至少有一个**（详见「符号」那一节）",
    ),
]

for name, old, new in EDITS:
    n = t.count(old)
    if n == 0:
        print(f"· {name}：锚点没命中（可能已改过），跳过")
        continue
    t = t.replace(old, new, 1)
    print(f"✓ {name}（{len(new) - len(old):+d} 字）")

if DRY:
    print("（dry-run，未写盘）")
else:
    P.write_text(t, encoding="utf-8")
    print(f"✓ 真源 {P.name}：{len(orig):,} → {len(t):,} 字")
