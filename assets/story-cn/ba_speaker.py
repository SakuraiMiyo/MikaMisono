# 老师（Sensei）在韩文脚本里的写法
SENSEI_KR = {"선생", "선생님", "센세이", "쌤"}


def parse_speaker(script_kr: str) -> tuple[str | None, str | None, str | None]:
    """解析一个单元的 ScriptKr。

    返回 `(说话人韩文原名, 说话人中译, 表情编号)`；本单元没有说话人时返回 `(None, None, None)`。

    两种带名字的写法都要认：

      `{槽位};{角色};{表情};{台词}`  立绘 + 台词（最常见）
      `#na;{角色};{台词}`            **角色旁白** —— 未花讲圣三一历史那种大段独白全走这个形式，
                                     早期版本漏了它，等于把她最长的一段台词整段丢掉。

    纯立绘/动作命令（无台词）不算台词。
    """
    if not script_kr:
        return None, None, None
    speaker = face = None
    for m in CMD.finditer(script_kr):
        text = (m.group(4) or "").strip()
        if not text:
            continue
        speaker, face = m.group(2).strip(), m.group(3)
    if speaker is None:
        for m in NA_NAMED.finditer(script_kr):
            name = m.group(1).strip()
            if NAME_OK.match(name):
                speaker, face = name, None
    if speaker is None:
        return None, None, None
    return speaker, speaker_cn(speaker), face


def speaker_cn(kr_name: str) -> str:
    if kr_name in SENSEI_KR:
        return "老师"
    for base, cn in SPEAKER_CN.items():
        if kr_name == base or kr_name.startswith(base + " "):
            return cn
    # 「XXX A」「XXX B」这类杂兵
    m = re.match(r"^(.*?)\s*([A-Z])$", kr_name)
    if m and m.group(1) in SPEAKER_CN:
        return f"{SPEAKER_CN[m.group(1)]} {m.group(2)}"
    return kr_name          # 未知名字原样保留，便于后续补映射


def is_mika(kr_name: str | None) -> bool:
    return bool(kr_name) and kr_name.split(" ")[0] == "미카"


def parse_emotes(script_kr: str, name: str | None = None) -> list[str]:
    """取该单元的情绪气泡。

    传了 `name`（韩文角色名）就只返回**该角色所在槽位**的气泡；
    不传则返回单元里所有角色的气泡。

    气泡形式：`#3;em;[하트]` —— 槽位 3 的角色头上冒一颗心。
    比立绘编号可靠得多：立绘编号只是立绘资源号，和情绪没有稳定对应。
    """
    if not script_kr:
        return []
    slots: set[str] = set()
    if name:
        for m in CMD.finditer(script_kr):
            if m.group(2).strip() == name:
                slots.add(m.group(1))
        for m in NA_NAMED.finditer(script_kr):
            if m.group(1).strip() == name:
                slots = set()          # 角色旁白没有槽位，退回全量
                break
    out = []
    for m in EMOTE.finditer(script_kr):
        if name and slots and m.group(1) not in slots:
            continue
        raw = m.group(2).strip()
        out.append(EMOTE_CN.get(raw, raw))
    return out


def clean_text(t: str) -> str:
    """把中文台词里的演出标记清干净（标记清单来自全库实测，见 README）。

    `[ruby=X]字[/ruby]` → `字`、`[tooltip=A]B[/tooltip]` → `B`、
    颜色码 `[FF6666]…[-]` 与 `[wa:1500]` 等待机指令直接删掉。
    """
    t = (t or "").replace("#n", "\n")
    t = re.sub(r"\[ruby=[^\]]*\]", "", t)
    t = re.sub(r"\[tooltip=[^\]]*\]", "", t)
    t = re.sub(r"\[wa:\d+\]", "", t)
    t = re.sub(r"\[log=[^\]]*\]", "", t)
    t = re.sub(r"\[/?(?:ruby|tooltip|log|b|i|u|size|color)\]", "", t)
    t = re.sub(r"\[-[^\]]*\]|\[-\]", "", t)          # 颜色段结束
    t = re.sub(r"\[[0-9A-Fa-f]{6}\]", "", t)          # 颜色段开始
    t = t.replace("[USERNAME]", "")
    t = re.sub(r"\.{2,}", "……", t)
    # 去掉行首说话人标记（[s] / [ns] / [s1] / [ns12] …）
    t = re.sub(r"^\[(?:s|ns)\d*\]\s*", "", t)
    t = "\n".join(ln.strip() for ln in t.split("\n") if ln.strip())
    # ruby 断字会留下「泳 衣」这种空档：两个汉字之间的空白直接吃掉
    t = re.sub(r"(?<=[\u4e00-\u9fff])\s+(?=[\u4e00-\u9fff])", "", t)
    return t.strip().strip('"').strip("“”").strip("＂").strip()


def speaker_of_unit(unit: dict) -> tuple[str, str, str | None]:
    """综合判定一个单元：返回 `(说话人中文名, 置信度 high/none, 韩文原名)`。

    判序（**ScriptKr 优先**，它是游戏原始演出脚本，最可靠）：

      1. `ScriptKr` 里 `槽位;角色名;表情;台词` → 精确说话人
      2. 中文侧 `[s]`      → 老师
      3. 中文侧 `[ns]`…    → 旁白
      4. 中文侧 `[s1]`…    → 多角色共用文本框，说话人未标明 → 置信度 none
      5. 都没有            → 未知
    """
    kr, _, _ = parse_speaker(unit.get("ScriptKr") or "")
    if kr:
        if kr in SENSEI_KR:
            return "老师", "high", kr
        return speaker_cn(kr), "high", kr

    cn = (unit.get("TextCn") or "").strip()
    if SENSEI_PREFIX.match(cn):
        return "老师", "high", None
    if MULTI_PREFIX.match(cn):
        return "（多人文本框）", "none", None
    if NARR_PREFIX.match(cn):
        return "旁白", "high", None
    return "未知", "none", None


def cjk_len(s: str) -> int:
    return sum(1 for ch in s if "\u4e00" <= ch <= "\u9fff")


